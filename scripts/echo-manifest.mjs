#!/usr/bin/env node
/**
 * Chain-timestamp the Season Zero manifest (MP-GAME.md §2, §4; MP-REVEAL.md
 * Phase B): the manifest's keccak256 is echoed in a zero-value transaction
 * from the treasury wallet to itself on chain 4663, so the commitment carries
 * a timestamp independent of git history. Gate B: no Archive Game clue drops
 * before this lands.
 *
 * The hash is computed over the manifest's RAW BYTES — never parse-and-
 * reserialize; the bytes on disk ARE the commitment (same law as
 * provenance.json and its onchain provenanceHash).
 *
 * Default mode (no key needed): print the manifest keccak256 and the exact
 * transaction to send. Mode --send: requires TREASURY_PRIVATE_KEY in the
 * environment, refuses any other signer, sends the echo, verifies the
 * receipt, and records it in echo.json beside the manifest.
 * --manifest <path> overrides the manifest location (default
 * game/season-zero/manifest.json).
 *
 * Never prints any key or env var value. Run: node scripts/echo-manifest.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { JsonRpcProvider, Wallet, keccak256 } from "ethers";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));

function loadDotEnv() {
  const p = resolve(root, ".env");
  if (!existsSync(p)) return;
  for (const line of readFileSync(p, "utf8").split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i < 1) continue;
    const k = t.slice(0, i).trim();
    let v = t.slice(i + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    if (process.env[k] === undefined) process.env[k] = v;
  }
}

loadDotEnv();

const RPC =
  process.env.RH_RPC_URL ||
  process.env.RPC_URL ||
  "https://rpc.mainnet.chain.robinhood.com";
const CHAIN_ID = 4663;
const TREASURY = "0xBCCAecdBb4F0c7af32C8018486D0b52A474d9B4a";
const EXPLORER = "https://robinhoodchain.blockscout.com";

// Strict argv (same approach as scripts/pin-mp-reveal.mjs): any argument that
// is not an exactly recognized flag, or a value consumed by one, is a loud
// HOLD before ANY network or key handling. A misspelled --manifest alongside
// --send would otherwise silently chain-echo the REAL Season Zero manifest.
const args = process.argv.slice(2);
let doSend = false;
let manifestPath = join(root, "game", "season-zero", "manifest.json");
for (let i = 0; i < args.length; i++) {
  const a = args[i];
  const eq = a.indexOf("=");
  const key = eq > 0 ? a.slice(0, eq) : a;
  const val = () => (eq > 0 ? a.slice(eq + 1) : args[++i]);
  if (a === "--send") doSend = true;
  else if (key === "--manifest") {
    const raw = val();
    if (!raw) {
      console.error("HOLD: --manifest needs a path.");
      console.error("usage: node scripts/echo-manifest.mjs [--manifest <path>] [--send]");
      process.exit(2);
    }
    manifestPath = resolve(raw);
  } else {
    console.error(`HOLD: unknown argument '${a}'. Nothing read, nothing sent.`);
    console.error("usage: node scripts/echo-manifest.mjs [--manifest <path>] [--send]");
    process.exit(2);
  }
}
const echoPath = join(dirname(manifestPath), "echo.json");

if (!existsSync(manifestPath)) {
  console.error(
    `No manifest at ${manifestPath}.\n` +
      "The Season Zero manifest is generated by the private Phase B script\n" +
      "(MP-REVEAL.md) — if that has not run yet, this is expected. Nothing to\n" +
      "hash, nothing to echo."
  );
  process.exit(2);
}

// RAW BYTES, straight off the disk. No JSON.parse, no reserialize — a single
// reordered key or rewritten line ending would change the commitment.
const bytes = readFileSync(manifestPath);
const hash = keccak256(bytes);

console.log("Manifest  :", manifestPath);
console.log("Bytes     :", bytes.length);
console.log("keccak256 :", hash);
console.log(`\nThe echo transaction (treasury -> itself, zero value, hash as calldata):`);
console.log(`  from    : ${TREASURY} (treasury)`);
console.log(`  to      : ${TREASURY} (itself)`);
console.log(`  value   : 0`);
console.log(`  data    : ${hash}`);
console.log(`  chainId : ${CHAIN_ID}`);
console.log(
  "\nSend it from any wallet holding the treasury key (custom hex data field),\n" +
    "or run: TREASURY_PRIVATE_KEY=... node scripts/echo-manifest.mjs --send"
);

if (existsSync(echoPath)) {
  const prior = JSON.parse(readFileSync(echoPath, "utf8"));
  if (prior.manifestKeccak256 === hash) {
    console.log(`\nAlready echoed: ${prior.txHash} (recorded in ${echoPath}).`);
  } else {
    console.log(
      `\nHOLD: ${echoPath} records a DIFFERENT manifest hash (${prior.manifestKeccak256}).\n` +
        "The manifest bytes changed after the echo was sent — that is a\n" +
        "stop-the-line event. Do not re-echo until this is understood."
    );
    process.exitCode = 1;
  }
}

if (!doSend) process.exit(process.exitCode ?? 0);

// ---- --send: sign the echo from the treasury --------------------------------
if (existsSync(echoPath)) {
  const prior = JSON.parse(readFileSync(echoPath, "utf8"));
  if (prior.manifestKeccak256 === hash) {
    console.log("\nRefusing to re-send: this exact manifest hash is already echoed.");
    process.exit(0);
  }
  console.error("\nRefusing to send over a mismatched echo.json (see HOLD above).");
  process.exit(1);
}

const rawKey = process.env.TREASURY_PRIVATE_KEY;
if (!rawKey) {
  console.error(
    "\nHOLD: TREASURY_PRIVATE_KEY is not set — nothing signed, nothing sent.\n" +
      "The echo must come from the treasury wallet; no other signer's\n" +
      "transaction satisfies the commitment. The .env PRIVATE_KEY (MP deployer)\n" +
      "is a different role and is deliberately not used."
  );
  process.exit(2);
}

// Pre-validate the key SHAPE before ethers ever sees it: ethers 6 embeds the
// malformed value in its invalid-BytesLike error message, so an uncaught
// new Wallet(key) would echo a nearly-real key (trailing newline, stray
// quote, 63-hex truncation) to stderr.
const key = rawKey.trim();
if (!/^(0x)?[0-9a-fA-F]{64}$/.test(key)) {
  console.error(
    "\nHOLD: TREASURY_PRIVATE_KEY is set but is not 64 hex characters\n" +
      "(optionally 0x-prefixed). The value is deliberately NOT printed.\n" +
      "Common causes: a trailing newline, a stray quote from copy-paste, or a\n" +
      "truncated key. Fix the env value and re-run. Nothing signed, nothing sent."
  );
  process.exit(2);
}

const provider = new JsonRpcProvider(RPC, CHAIN_ID);
let signer;
try {
  signer = new Wallet(key, provider);
} catch {
  // Never interpolate the key OR the caught error here — ethers embeds the
  // offending value in err.message too.
  console.error(
    "\nHOLD: TREASURY_PRIVATE_KEY passed the shape check but ethers refused to\n" +
      "construct a wallet from it (the value and the underlying error message\n" +
      "are deliberately NOT printed). Nothing signed, nothing sent."
  );
  process.exit(2);
}
const signerAddress = await signer.getAddress();
if (signerAddress.toLowerCase() !== TREASURY.toLowerCase()) {
  console.error(
    `\nHOLD: TREASURY_PRIVATE_KEY derives to ${signerAddress},\n` +
      `not the treasury ${TREASURY}.\n` +
      "Refusing to sign — MP-GAME.md commits the echo to the treasury wallet\n" +
      "specifically. Check which key you exported."
  );
  process.exit(1);
}
console.log("\nSigner  :", signerAddress, "(verified treasury)");

const tx = await signer.sendTransaction({ to: TREASURY, value: 0n, data: hash });
console.log("Sent    :", tx.hash);
const receipt = await tx.wait();
console.log("Mined   : block", receipt.blockNumber);

const record = {
  manifestKeccak256: hash,
  txHash: receipt.hash,
  blockNumber: receipt.blockNumber,
  from: signerAddress,
  sentAt: new Date().toISOString(),
  explorer: `${EXPLORER}/tx/${receipt.hash}`,
};
writeFileSync(echoPath, JSON.stringify(record, null, 2) + "\n");
console.log(`\nEcho recorded in ${echoPath}:`);
console.log(JSON.stringify(record, null, 2));
console.log("\nGate B is satisfied once this file and the manifest are published.");
process.exit(0);
